import assert from 'node:assert/strict';
import {createRoomStore} from './room-snapshots.mjs';
const store=createRoomStore('friends');
const room={id:'demo-1',game:'斗地主',players:1,capacity:3};
const snap=(revision,rooms=[room])=>({scope:'friends',revision,rooms});
assert.equal(store.read().revision,-1);
assert.equal(store.apply(snap(2)),true);
assert.equal(store.apply(snap(1)),false);
assert.equal(store.apply(snap(2)),false);
assert.equal(store.apply({...snap(3),scope:'other'}),false);
assert.throws(()=>store.apply(snap(3,[room,room])),/duplicate/);
assert.equal(store.read().revision,2);
assert.throws(()=>store.apply(snap(3,[{...room,players:4}])),/invalid room/);
assert.throws(()=>store.apply(snap(-1)),/invalid revision/);
assert.throws(()=>store.apply(snap(2.5)),/invalid revision/);
room.players=2;
assert.equal(store.read().rooms[0].players,1);
const read=store.read();read.rooms[0].players=3;
assert.equal(store.read().rooms[0].players,1);
assert.equal(store.apply(snap(3,[])),true);
assert.deepEqual(store.read().rooms,[]);
console.log('14 assertions passed');
